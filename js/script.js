// 언어 변경 함수
function changeLanguage(lang) {
  const content = translations[lang];

  // HTML 언어 설정
  document.documentElement.lang = lang;

  // 텍스트 변경
  document.getElementById('page-title').innerHTML = content.pageTitle;

  document.getElementById('subtitle').innerHTML = content.subtitle;

  document.getElementById('behind-title').innerHTML = content.behindTitle;

  document.getElementById('behind-text').innerHTML = content.behindText;

  document.getElementById('tal-title').innerHTML = content.talTitle;

  document.getElementById('tal-text').innerHTML = content.talText;

  document.getElementById('show-title').innerHTML = content.showTitle;

  document.getElementById('show-text').innerHTML = content.showText;

  document.getElementById('pdf-title').innerHTML = content.pdfTitle;

  document.getElementById('download-btn').innerHTML = content.downloadText;

  document.getElementById('footer-text').innerHTML = content.footerText;

  // PDF 뷰어 변경
  document.getElementById('pdf-viewer').src = content.pdf;

  // 다운로드 링크 변경
  document.getElementById('download-btn').href = content.pdf;

  // 선택된 언어 버튼 표시
  document.getElementById('ko-btn').classList.toggle('active', lang === 'ko');

  document.getElementById('ja-btn').classList.toggle('active', lang === 'ja');
}
